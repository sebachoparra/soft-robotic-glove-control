/* ukf_shadow_rp2040.h:393-408 */
float sgc_lut(const float *table, float s)
{
  s = sgc_clampf(s, SGC_UKF_MODEL_S_MIN, SGC_UKF_MODEL_S_MAX);

  if (s >= SGC_UKF_MODEL_S_MAX) {
    return table[SGC_UKF_MODEL_N - 1];
  }

  int i = (int)s;

  if (i < 0) {i = 0;}
  if (i >= SGC_UKF_MODEL_N - 1) {i = SGC_UKF_MODEL_N - 2;}

  float a = s - (float)i;

  return table[i] + a * (table[i + 1] - table[i]);
}

/* =================================================================
 * BLOCK 2: PLANT SCHEDULE EVALUATION
 * ================================================================= */

/* plant_schedule.h:15-42 */
bool sgc_plant_schedule_eval(float q, float eta, SgcPlantSchedule *out)
{
  if (!out || !isfinite(q) || !isfinite(eta)) {return false;}
  float qc = fminf(fmaxf(q, sgc_plant_anchors[0].q),
                      sgc_plant_anchors[SGC_PLANT_ANCHOR_COUNT - 1].q);
  float h = fminf(fmaxf(eta, 0.0f), 1.0f);
  unsigned i = 0;
  while (i + 2 < SGC_PLANT_ANCHOR_COUNT && qc > sgc_plant_anchors[i + 1].q) {++i;}
  const SgcPlantAnchor *a = &sgc_plant_anchors[i], *b = &sgc_plant_anchors[i + 1];
  if (!(b->q > a->q) || !(a->k_up > 0) || !(b->k_up > 0) ||
    !(a->k_down > 0) || !(b->k_down > 0) ||
    !(a->tau_up > 0) || !(b->tau_up > 0) ||
    !(a->tau_down > 0) || !(b->tau_down > 0)) {return false;}
  float w = (qc - a->q) / (b->q - a->q);
  float ku = (1 - w) * logf(a->k_up) + w * logf(b->k_up);
  float kd = (1 - w) * logf(a->k_down) + w * logf(b->k_down);
  float tu = (1 - w) * logf(a->tau_up) + w * logf(b->tau_up);
  float td = (1 - w) * logf(a->tau_down) + w * logf(b->tau_down);
  SgcPlantSchedule r = {0};
  r.q = qc; r.eta = h; r.clamped = qc != q || h != eta;
  r.k = expf((1 - h) * ku + h * kd);
  r.tau = expf((1 - h) * tu + h * td);
  r.ki = SGC_PLANT_P1 / r.k; r.kp = r.ki * r.tau; r.b0 = r.k / r.tau;
  if (!isfinite(r.kp) || !isfinite(r.ki) || !isfinite(r.b0) ||
    !(r.kp > 0) || !(r.ki > 0) || !(r.b0 > 0)) {return false;}
  *out = r;
  return true;
}

